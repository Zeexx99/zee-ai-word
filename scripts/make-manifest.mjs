// Usage: node scripts/make-manifest.mjs https://<user>.github.io/zee-ai-word
// Writes manifest.prod.xml pointing at the hosted URL (separate add-in Id from the dev manifest,
// so the local and hosted versions never overwrite each other in Word).
import { readFileSync, writeFileSync } from "node:fs";

const base = (process.argv[2] || "").replace(/\/+$/, "");
if (!/^https:\/\/[^\s]+$/.test(base)) {
  console.error("Usage: node scripts/make-manifest.mjs https://<user>.github.io/zee-ai-word");
  process.exit(1);
}
const PROD_ID = "b11d1949-ce15-4782-a44d-becdb2eb4652";
let xml = readFileSync(new URL("../manifest.xml", import.meta.url), "utf8");
xml = xml
  .replaceAll("https://localhost:3200", base)
  .replace(/<Id>[^<]+<\/Id>/, `<Id>${PROD_ID}</Id>`)
  .replace(/<!--[\s\S]*?-->\s*/, "<!-- Zee AI for Word - hosted manifest (generated by scripts/make-manifest.mjs). -->\n");
writeFileSync(new URL("../manifest.prod.xml", import.meta.url), xml);
console.log(`manifest.prod.xml written for ${base}`);
